const dict: Record<Lang, Record<string, string>> = { en, es }

function readLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'es' || v === 'en') return v
  } catch {
    /* ignore */
  }
  return 'en'
}

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

const I18nContext = createContext<{
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
}>({
  lang: 'en',
  setLang: () => undefined,
  t: (key, vars) => interpolate(dict.en[key] ?? key, vars),
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])
  const value = useMemo(() => {
    function setLang(next: Lang) {
      setLangState(next)
      try {
        localStorage.setItem(STORAGE_KEY, next)
      } catch {
        /* ignore */
      }
    }
    function t(key: string, vars?: Record<string, string | number>) {
      return interpolate(dict[lang][key] ?? dict.en[key] ?? key, vars)
    }
    return { lang, setLang, t }
  }, [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useT() {
  return useContext(I18nContext)
}

export function LanguageToggle({ className }: { className?: string }) {
  const { lang, setLang, t } = useT()
  return (
    <div className={className ?? 'inline-flex overflow-hidden rounded-md border border-line text-xs'} role="group" aria-label={`${t('lang.en')} / ${t('lang.es')}`}>
      <button
        type="button"
        className={`px-2 py-1 ${lang === 'en' ? 'bg-gold text-bg' : 'text-muted hover:bg-panel-2'}`}
        onClick={() => setLang('en')}
        aria-pressed={lang === 'en'}
      >
        EN
      </button>
      <button
        type="button"
        className={`px-2 py-1 ${lang === 'es' ? 'bg-gold text-bg' : 'text-muted hover:bg-panel-2'}`}
        onClick={() => setLang('es')}
        aria-pressed={lang === 'es'}
      >
        ES
      </button>
    </div>
  )
}
